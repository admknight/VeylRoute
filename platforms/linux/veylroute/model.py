"""Pure, testable Linux routing plans. No network mutations in this module."""
from __future__ import annotations

import ipaddress
import re
from dataclasses import dataclass

APP = "veylroute"
TOR_USER = "veylroute-tor"
RUN_DIR = "/run/veylroute"
DATA_DIR = "/var/lib/veylroute/tor-data"
NAT_TABLE = "veylroute_nat"
GUARD_TABLE = "veylroute_guard"
TOR_SOCKS_PORT = 39050
TOR_TRANS_PORT = 39040
TOR_DNS_PORT = 39053
BOOTSTRAP_TIMEOUT = 240


@dataclass(frozen=True)
class Options:
    exit_country: str = "auto"
    bridges: tuple[str, ...] = ()

    def validate(self) -> "Options":
        country = self.exit_country.strip().upper()
        if country != "AUTO" and not re.fullmatch(r"[A-Z]{2}", country):
            raise ValueError("Exit country must be 'auto' or a two-letter ISO country code")
        if len(self.bridges) > 25:
            raise ValueError("Too many bridge lines")
        for line in self.bridges:
            validate_bridge(line)
        return Options(country.lower() if country == "AUTO" else country, self.bridges)


def validate_bridge(line: str) -> str:
    """Reject torrc-injection and malformed/non-obfs4 bridge rows.

    A bridge is an entire user-provided line; do not publish, log or
    include private bridge credentials in diagnostics.
    """
    if (not isinstance(line, str) or len(line) > 400 or "\n" in line or "\r" in line
            or "\x00" in line or "#" in line):
        raise ValueError("Invalid bridge line")
    clean = line.strip()
    # Only supported transport here is obfs4; enforce port, fingerprint,
    # cert and iat-mode forms. IPv6 bridges are deliberately deferred.
    regex = (r"(?:Bridge\s+)?obfs4\s+(?:\d{1,3}\.){3}\d{1,3}:\d{1,5}"
             r"\s+[0-9A-Fa-f]{40}\s+cert=[A-Za-z0-9+/=-]{40,}"
             r"\s+iat-mode=[012]")
    if not re.fullmatch(regex, clean):
        raise ValueError("Expected obfs4 IPv4:port, fingerprint, cert and iat-mode")
    pieces = clean.split()
    endpoint = pieces[2] if pieces[0] == "Bridge" else pieces[1]
    addr, port = endpoint.rsplit(":", 1)
    if not ipaddress.IPv4Address(addr) or not (1 <= int(port) <= 65535):
        raise ValueError("Invalid bridge endpoint")
    return clean if clean.startswith("Bridge ") else "Bridge " + clean


def build_torrc(options: Options, tor_data: str = DATA_DIR) -> str:
    opt = options.validate()
    # Paths fixed by package, never interpolated from user input.
    lines = [
        "# Generated by VeylRoute Linux. Do not edit while connected.",
        f"DataDirectory {tor_data}",
        f"PidFile {tor_data}/tor.pid",
        f"SocksPort 127.0.0.1:{TOR_SOCKS_PORT}",
        f"TransPort 127.0.0.1:{TOR_TRANS_PORT}",
        f"DNSPort 127.0.0.1:{TOR_DNS_PORT}",
        "VirtualAddrNetworkIPv4 10.192.0.0/10",
        "AutomapHostsOnResolve 1",
        "AutomapHostsSuffixes .",
        "ClientUseIPv6 0",
        "ClientOnly 1",
        f"ControlSocket {tor_data}/control.socket",
        "CookieAuthentication 1",
        f"CookieAuthFile {tor_data}/control.authcookie",
        "Log notice stdout",
    ]
    if opt.exit_country != "auto":
        lines += [f"ExitNodes {{{opt.exit_country.lower()}}}", "StrictNodes 1"]
    if opt.bridges:
        lines += ["UseBridges 1", "ClientTransportPlugin obfs4 exec /usr/bin/obfs4proxy"]
        lines += [validate_bridge(s) for s in opt.bridges]
    return "\n".join(lines) + "\n"


def build_nft_plan(tor_uid: int) -> str:
    """Two isolated tables committed in *one* nft transaction.

    IPv4 TCP is redirected to Tor TransPort, DNS UDP/53 to DNSPort;
    other outgoing traffic (including IPv6, QUIC, multicast, raw
    sockets) fails closed, except local loopback and Tor's dedicated UID.
    No existing nft tables, routes or system resolver files are altered.

    Caveats: only broadcast DHCPv4 is exempt; unicast renewal may be
    disrupted. Local Unix socket relay apps are outside an OUTPUT filter.
    """
    if isinstance(tor_uid, bool) or not isinstance(tor_uid, int) or tor_uid < 1:
        raise ValueError("Dedicated unprivileged Tor UID required")
    return f"""# VeylRoute managed tables; do not flush other firewall tables.
table ip {NAT_TABLE} {{
    chain output {{
        type nat hook output priority dstnat; policy accept;
        meta skuid {tor_uid} return
        ip daddr 127.0.0.0/8 return
        udp dport 53 redirect to :{TOR_DNS_PORT}
        meta l4proto tcp redirect to :{TOR_TRANS_PORT}
    }}
}}
table inet {GUARD_TABLE} {{
    chain output {{
        type filter hook output priority filter; policy accept;
        oifname "lo" accept
        meta skuid {tor_uid} accept
        ip daddr 255.255.255.255 udp dport 67 accept
        meta l4proto {{ tcp, udp }} counter drop
        counter drop
    }}
}}
"""


def guard_present(table_names: str) -> bool:
    return f"table inet {GUARD_TABLE}" in table_names


def nat_present(table_names: str) -> bool:
    return f"table ip {NAT_TABLE}" in table_names


def snapshot_compare(before: dict, after: dict) -> dict:
    """Read-only baseline comparison. Report drift; never restore OS state blindly."""
    keys = ("ipv4_routes", "ipv6_routes", "dns_state")
    return {key: before.get(key) == after.get(key) for key in keys}
